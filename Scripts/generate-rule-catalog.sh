#!/usr/bin/env sh
# Regenerates Sources/BouncerReporting/RuleCatalogText.swift and RuleExamplesText.swift from the rule catalog and
# rule examples articles, so the binary can explain any rule (`explain_rule` in `bouncer mcp`, the HTML report's
# tooltips and example diffs) without shipping resources. Run it after editing either article; RuleCatalogTests
# fails while an embedded copy is out of date.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ARTICLES="${ROOT}/Sources/BouncerCore/BouncerCore.docc/Articles"

# Prints the '#' run a raw string around an article needs: one more than the longest '"#…' or '\#…' run in
# the text, so nothing inside can close it or read as an escape. hashes <article path>.
hashes() {
    LONGEST="$(grep -o '["\\]#*' "$1" | awk '{ if (length($0) > max) max = length($0) } END { print max + 0 }')"
    awk -v count="$LONGEST" 'BEGIN { if (count < 1) count = 1; for (i = 0; i < count; i++) printf "#" }'
}

# Prints the Swift file embedding one article as a string: swift_text <article name> <enum name>.
swift_text() {
    HASHES="$(hashes "${ARTICLES}/$1.md")"
    printf '/// The %s article, embedded so the binary can explain rules without bundled resources.\n///\n' "$1"
    printf '/// Generated by Scripts/generate-rule-catalog.sh from\n'
    printf '/// Sources/BouncerCore/BouncerCore.docc/Articles/%s.md. Do not edit by hand.\n' "$1"
    echo "enum $2 {"
    echo '    /// The article'"'"'s Markdown, verbatim.'
    echo "    static let markdown = ${HASHES}\"\"\""
    cat "${ARTICLES}/$1.md"
    printf '\n"""%s\n}\n' "$HASHES"
}

# Embeds one article as a Swift string: embed <article name> <enum name>.
embed() {
    swift_text "$1" "$2" > "${ROOT}/Sources/BouncerReporting/$2.swift"
    echo "Wrote ${ROOT}/Sources/BouncerReporting/$2.swift"
}

embed RuleCatalog RuleCatalogText
embed RuleExamples RuleExamplesText
