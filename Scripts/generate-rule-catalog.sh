#!/usr/bin/env sh
# Regenerates Sources/BouncerReporting/RuleCatalogText.swift from the rule catalog article, so the binary
# can explain any rule (`explain_rule` in `bouncer mcp`) without shipping resources. Run it after editing
# RuleCatalog.md; RuleCatalogTests fails while the embedded copy is out of date.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SOURCE="${ROOT}/Sources/BouncerCore/BouncerCore.docc/Articles/RuleCatalog.md"
OUT="${ROOT}/Sources/BouncerReporting/RuleCatalogText.swift"

# A raw string needs one more '#' than the longest '"#…' or '\#…' run in the text, so nothing inside can
# close it or read as an escape.
LONGEST="$(grep -o '["\\]#*' "$SOURCE" | awk '{ if (length($0) > max) max = length($0) } END { print max + 0 }')"
HASHES="$(awk -v count="$LONGEST" 'BEGIN { if (count < 1) count = 1; for (i = 0; i < count; i++) printf "#" }')"

{
    echo '/// The rule catalog article, embedded so the binary can explain rules without bundled resources.'
    echo '///'
    echo '/// Generated by Scripts/generate-rule-catalog.sh from'
    echo '/// Sources/BouncerCore/BouncerCore.docc/Articles/RuleCatalog.md. Do not edit by hand.'
    echo 'enum RuleCatalogText {'
    echo '    /// The article'"'"'s Markdown, verbatim.'
    echo "    static let markdown = ${HASHES}\"\"\""
    cat "$SOURCE"
    echo
    echo "\"\"\"${HASHES}"
    echo '}'
} > "$OUT"

echo "Wrote ${OUT}"
