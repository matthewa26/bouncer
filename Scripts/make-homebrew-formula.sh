#!/usr/bin/env sh
# Writes the Homebrew formula for a release to stdout, from the release's SHA256SUMS. The formula
# installs the prebuilt binaries: the universal macOS build, and the static Linux builds for x86_64
# and arm64. The release workflow runs it and pushes the result to the tap (matthewa26/homebrew-tap).
#
# Usage: make-homebrew-formula.sh <tag, e.g. v1.2.0> <SHA256SUMS> [owner/repo]
set -eu
TAG="${1:?usage: make-homebrew-formula.sh <tag> <SHA256SUMS> [owner/repo]}"
SUMS="${2:?usage: make-homebrew-formula.sh <tag> <SHA256SUMS> [owner/repo]}"
REPO="${3:-matthewa26/bouncer}"
BASE="https://github.com/${REPO}/releases/download/${TAG}"

# Prints one archive's checksum, failing if SHA256SUMS doesn't list it.
sum() {
    line=$(grep " \*\{0,1\}bouncer-$1.tar.gz\$" "$SUMS") || { echo "SHA256SUMS has no bouncer-$1.tar.gz" >&2; exit 1; }
    echo "${line%% *}"
}
MACOS=$(sum macos-universal)
LINUX_X86=$(sum linux-x86_64)
LINUX_ARM=$(sum linux-arm64)

cat <<RUBY
# Generated by Scripts/make-homebrew-formula.sh in ${REPO}; the release workflow overwrites it.
class Bouncer < Formula
  desc "Code-quality gate with a pre-commit check and an MCP server for agents"
  homepage "https://matthewa26.github.io/bouncer/"
  license "GPL-3.0-or-later"

  if OS.mac?
    url "${BASE}/bouncer-macos-universal.tar.gz"
    sha256 "${MACOS}"
  elsif Hardware::CPU.arm?
    url "${BASE}/bouncer-linux-arm64.tar.gz"
    sha256 "${LINUX_ARM}"
  else
    url "${BASE}/bouncer-linux-x86_64.tar.gz"
    sha256 "${LINUX_X86}"
  end

  def install
    bin.install "bouncer"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/bouncer --version")
  end
end
RUBY
