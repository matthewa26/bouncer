import Foundation
import BouncerCore

/// What one rule checks and how to configure or silence it, as compact plain text for a coding agent.
public struct RuleExplanation: Sendable, Equatable {
    /// The rule's ID.
    public let id: String
    /// The explanation: the rule's catalog section, why it matters, each catalog row that documents it, its OWASP
    /// category when it has one, and how to configure it in `.bouncer` or suppress one finding inline.
    public let text: String
}

/// The rule catalog article, available at runtime, so a caller such as `bouncer mcp` can explain any rule.
///
/// The article's Markdown is embedded in the binary (`RuleCatalogText`, generated by
/// `Scripts/generate-rule-catalog.sh`) and its tables are parsed once, the first time they're needed.
public enum RuleCatalog {
    /// Every catalog row that names a rule, keyed by rule ID, in the order the article lists them.
    private static let rowsByRule: [String: [CatalogRow]] = {
        let rows = RuleCatalogParser.rows(in: RuleCatalogText.markdown)
        let pairs = rows.flatMap { row in row.ruleIDs.map { (id: $0, row: row) } }
        return Dictionary(grouping: pairs, by: \.id).mapValues { $0.map(\.row) }
    }()

    /// Every rule ID the catalog documents, sorted.
    private static let sortedRuleIDs: [String] = rowsByRule.keys.sorted()

    /// Explains one rule from the catalog.
    ///
    /// - Parameter ruleID: The rule's ID, matched exactly.
    /// - Returns: The explanation, or `nil` if the catalog doesn't document that rule.
    public static func explain(_ ruleID: String) -> RuleExplanation? {
        guard let rows = rowsByRule[ruleID] else { return nil }
        return RuleExplanation(id: ruleID, text: RuleExplanationWriter(ruleID: ruleID, rows: rows).text)
    }

    /// Every rule ID the catalog documents, sorted and without duplicates.
    public static var ruleIDs: [String] {
        sortedRuleIDs
    }
}
