import XCTest
import Foundation
import BouncerCore
@testable import BouncerProject

/// The exceptions the design rules make after running over real code.
final class DesignRulesTuningTests: XCTestCase {
    private let root = URL(fileURLWithPath: "/nonexistent-repo")

    private func file(_ path: String, functions: [FunctionFact] = [], types: [TypeFact] = [], generated: Bool = false) -> FileFacts {
        FileFacts(path: path, contentHash: "h", module: ModuleFacts(
            imports: [], structure: StructureFacts(types: types, functions: functions, isGenerated: generated)
        ))
    }

    private func findings(_ ruleID: String, _ files: [FileFacts], configured: Bool = false) -> [Finding] {
        let settings = configured
            ? [ruleID: RuleSettings(enabled: true, severity: .warning, parameters: RuleParameters(values: [:]))] : [:]
        let context = AnalysisContext(repoRoot: root, ruleSettings: settings)
        return ProjectRules().findings(for: files, targets: [], context: context).filter { $0.ruleID == ruleID }
    }

    func testGeneratedAndDocCFilesAreLeftAlone() {
        let clump = ["a:Int", "b:Int", "c:Int"]
        let files = (1...4).map { file("gen\($0).swift", functions: [FunctionFact(name: "f\($0)", line: 1, parameters: clump)], generated: true) }
            + (1...4).map { file("Sources/A/A.docc/Resources/step\($0).swift", functions: [FunctionFact(name: "g\($0)", line: 1, parameters: clump)]) }
        XCTAssertTrue(findings("data-clump", files).isEmpty)
        let handWritten = (1...4).map { file("f\($0).swift", functions: [FunctionFact(name: "f\($0)", line: 1, parameters: clump)]) }
        XCTAssertEqual(findings("data-clump", handWritten).count, 1)
    }

    func testNumberedParametersAreAnOverloadSetNotAClump() {
        let numbered = ["spec1:TokenSpec", "spec2:TokenSpec", "spec3:TokenSpec"]
        let files = (1...4).map { file("f\($0).swift", functions: [FunctionFact(name: "at\($0)", line: 1, parameters: numbered)]) }
        XCTAssertTrue(findings("data-clump", files).isEmpty)
    }

    func testConventionallyNamedProtocolsAreNotSpeculative() {
        let types = [
            TypeFact(name: "AnyOptionGroup", line: 1, kind: .protocol), TypeFact(name: "ArrayWrapperProtocol", line: 2, kind: .protocol),
            TypeFact(name: "OptionGroup", line: 3, kind: .struct, members: TypeMembers(supertypes: ["AnyOptionGroup"])),
            TypeFact(name: "ArrayWrapper", line: 4, kind: .struct, members: TypeMembers(supertypes: ["ArrayWrapperProtocol"]))
        ]
        XCTAssertTrue(findings("single-implementation-interface", [file("a.swift", types: types)], configured: true).isEmpty)
    }

    func testTerminologySkipsBareVerbsDictatedNamesAndAdjectives() {
        let names = ["makeA", "makeB", "build", "buildBlock", "buildExpression", "newFile", "newSymbol", "make"]
        let files = [file("src/x/a.ts", functions: names.enumerated().map { FunctionFact(name: $0.element, line: $0.offset + 1) })]
        XCTAssertTrue(findings("inconsistent-terminology", files, configured: true).isEmpty)
    }

    func testCaseLabelsDropQualifiersButKeepStrings() {
        XCTAssertEqual(FactText.caseLabel("events.Created"), "Created")
        XCTAssertEqual(FactText.caseLabel(".circle(let r)"), "circle")
        XCTAssertEqual(FactText.caseLabel("let .circle(r)"), "circle")
        XCTAssertEqual(FactText.caseLabel("\"a.b\""), "\"a.b\"")
        XCTAssertNil(FactText.caseLabel("_"))
        XCTAssertEqual(FactText.subject("(this.state.kind)"), "state.kind")
        XCTAssertNil(FactText.subject("(a, b)"))
        XCTAssertTrue(FactText.isGenerated("// Code generated by protoc. DO NOT EDIT.\npackage x\n"))
        XCTAssertFalse(FactText.isGenerated(String(repeating: "\n", count: 11) + "// DO NOT EDIT"))
    }

    func testPublicAPIGrowthAlignsSymbolsSoAnInsertedOneIsReported() {
        let before = ["Store", "line", "Item", "line"].enumerated().map { ExportFact(name: $0.element, line: $0.offset + 1) }
        let after = ["Store", "line", "Type", "line", "Item", "line"].enumerated().map { ExportFact(name: $0.element, line: $0.offset + 1) }
        XCTAssertEqual(PublicAPIGrowthRule.added(before: before, after: after).map(\.line), [3, 4])
        XCTAssertEqual(PublicAPIGrowthRule.symbols(ModuleFacts(imports: [], exports: [ExportFact(name: "encode", line: 1)]), path: "a.swift"), [])
    }

    func testScriptsThatPreloadAPackageCountAsUsingIt() throws {
        let manifest = try XCTUnwrap(NPMManifest(text: #"{"scripts": {"start": "node -r dotenv/config x.js"}, "dependencies": {"dotenv": "1", "pg": "1"}}"#))
        XCTAssertTrue(manifest.isExempt("dotenv"))
        XCTAssertFalse(manifest.isExempt("pg"))
    }
}
